def load_register(root: Path = ROOT) -> dict[str, Any]:
    return json.loads((root / REGISTER).read_text(encoding="utf-8"))


def _name(node: ast.AST) -> str:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        return f"{_name(node.value)}.{node.attr}"
    return ast.unparse(node)


def _functions(tree: ast.AST, prefix: str = "") -> dict[str, ast.AST]:
    result = {}
    for node in getattr(tree, "body", ()):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            symbol = f"{prefix}.{node.name}" if prefix else node.name
            result[symbol] = node
            result.update(_functions(node, symbol))
    return result


def signature(node: ast.AST) -> dict[str, Any]:
    """Compare parameter kind, requiredness and annotation, without line numbers."""
    args = node.args
    parameters = []
    positional = [*args.posonlyargs, *args.args]
    defaults = [None] * (len(positional) - len(args.defaults)) + list(args.defaults)
    grouped = [
        (
            arg,
            "positional_only" if index < len(args.posonlyargs) else "positional_or_keyword",
            default,
        )
        for index, (arg, default) in enumerate(zip(positional, defaults, strict=True))
    ]
    if args.vararg:
        grouped.append((args.vararg, "var_positional", None))
    grouped.extend(
        (arg, "keyword_only", default)
        for arg, default in zip(args.kwonlyargs, args.kw_defaults, strict=True)
    )
    if args.kwarg:
        grouped.append((args.kwarg, "var_keyword", None))
    for arg, kind, default in grouped:
        parameters.append(
            {
                "name": arg.arg,
                "kind": kind,
                "required": default is None and kind not in {"var_positional", "var_keyword"},
                "default": ast.unparse(default) if default is not None else None,
                "annotation": ast.unparse(arg.annotation) if arg.annotation else None,
            }
        )
    return {
        "parameters": parameters,
        "returns": ast.unparse(node.returns) if node.returns else None,
    }


def _calls(node: ast.AST) -> list[ast.Call]:
    # Preorder preserves statement/call order; ast.walk uses breadth-first order.
    result = []
    for child in ast.iter_child_nodes(node):
        if isinstance(child, ast.Call):
            result.append(child)
        result.extend(_calls(child))
    return result


def _parse_source(
    root: Path, relative: str, trees: dict[str, ast.Module | OSError | SyntaxError]
) -> ast.Module:
    if relative not in trees:
        try:
            trees[relative] = ast.parse(
                (root / relative).read_text(encoding="utf-8"), filename=relative
            )
        except (OSError, SyntaxError) as error:
            trees[relative] = error
            raise
    tree = trees[relative]
    if isinstance(tree, (OSError, SyntaxError)):
        raise tree
    return tree


def source_inventory(root: Path = ROOT) -> dict[str, list[str]]:
    """Inventory production source, including routes not mounted in today's app."""
    return _source_inventory(root, {})


def _source_inventory(
    root: Path, trees: dict[str, ast.Module | OSError | SyntaxError]
) -> dict[str, list[str]]:
    routes, launches, services = [], [], []
    for package in PACKAGES:
        for path in sorted((root / package).rglob("*.py")):
            relative = path.relative_to(root).as_posix()
            if {"tests", "e2e", "__pycache__"}.intersection(
                path.relative_to(root).parts
            ) or relative == "foxprofile_ext/compatibility.py":
                continue
            tree = _parse_source(root, relative, trees)
            functions = _functions(tree)
            for symbol, node in functions.items():
                if isinstance(node, ast.ClassDef):
                    continue
                if relative in SERVICE_CLASSES:
                    owner, _, method = symbol.rpartition(".")
                    if owner == SERVICE_CLASSES[relative] and not method.startswith("_"):
                        services.append(f"{relative}:{symbol}")
                for decorator in node.decorator_list:
                    if (
                        isinstance(decorator, ast.Call)
                        and _name(decorator.func).split(".")[-1] in ROUTE_DECORATORS
                    ):
                        routes.append(f"{relative}:{symbol}:{ast.unparse(decorator)}")
            # Visit once, retaining lexical ownership, including module-level factories.
            aliases = {}
            for node in ast.walk(tree):
                if isinstance(node, ast.Import):
                    for imported in node.names:
                        aliases[imported.asname or imported.name] = imported.name
                elif isinstance(node, ast.ImportFrom) and node.module:
                    for imported in node.names:
                        aliases[imported.asname or imported.name] = f"{node.module}.{imported.name}"

            class Calls(ast.NodeVisitor):
                def __init__(self, filename, imported_names):
                    self.filename = filename
                    self.imported_names = imported_names
                    self.scope: list[str] = []

                def visit_FunctionDef(self, node):
                    self.scope.append(node.name)
                    self.generic_visit(node)
                    self.scope.pop()

                visit_AsyncFunctionDef = visit_FunctionDef
                visit_ClassDef = visit_FunctionDef

                def visit_Call(self, node):
                    name = _name(node.func)
                    head, separator, remainder = name.partition(".")
                    if head in self.imported_names:
                        name = self.imported_names[head] + (
                            separator + remainder if separator else ""
                        )
                    tail = name.split(".")[-1]
                    owner = ".".join(self.scope) or "<module>"
                    if tail in BROWSER_CALLS or (
                        tail in PROCESS_CALLS
                        and (
                            isinstance(node.func, ast.Name)
                            or name.startswith(
                                (
                                    "subprocess.",
                                    "asyncio.",
                                    "os.",
                                    "multiprocessing.",
                                    "concurrent.futures.",
                                )
                            )
                        )
                    ):
                        launches.append(f"{self.filename}:{owner}:{name}")
                    if tail in ROUTE_REGISTRATIONS:
                        routes.append(f"{self.filename}:{owner}:{ast.unparse(node)}")
                    self.generic_visit(node)

            Calls(relative, aliases).visit(tree)
    return {
        "source_routes": sorted(routes),
        "launch_calls": sorted(launches),
        "service_methods": sorted(services),
    }


def route_inventory(app: Any) -> list[dict[str, Any]]:
    """Read effective FastAPI routes, including inherited dependencies and WS.

    FastAPI versions with lazy router inclusion expose effective_route_contexts;
    older versions already contain their flattened routes.
    """
    routes = []
    for route in app.routes:
        effective = getattr(route, "effective_route_contexts", None)
        routes.extend(effective() if effective else [route])
    inventory = []
    for route in routes:
        original = getattr(route, "original_route", route)
        effective = getattr(route, "starlette_route", None) or route
        endpoint = getattr(route, "endpoint", None) or getattr(effective, "endpoint", None)
        if endpoint is None:
            symbol = (
                type(getattr(original, "app", None)).__module__
                + "."
                + type(getattr(original, "app", None)).__qualname__
            )
        else:
            symbol = f"{endpoint.__module__}.{getattr(endpoint, '__qualname__', type(endpoint).__qualname__)}"
        dependencies = []
        pending = list(getattr(getattr(route, "dependant", None), "dependencies", ()))
        while pending:
            dependency = pending.pop()
            dependencies.append(f"{dependency.call.__module__}.{dependency.call.__qualname__}")
            pending.extend(dependency.dependencies)
        methods = getattr(route, "methods", None) or getattr(effective, "methods", None)
        if methods:
            protocol = "http"
        elif hasattr(original, "app") and endpoint is None:
            protocol = "mount"
        else:
            protocol = "websocket"
        path = getattr(route, "path", None) or getattr(effective, "path", None)
        if path is None:
            raise ValueError("Unsupported route descriptor")
        for method in sorted(methods or {"*"}):
            inventory.append(
                {
                    "key": f"{protocol.upper()} {method} {path}",
                    "endpoint": symbol,
                    "dependencies": sorted(set(dependencies)),
                }
            )
    return sorted(inventory, key=lambda route: route["key"])


def check_source_contracts(root: Path = ROOT) -> list[str]:
    register = load_register(root)
    problems = []
    trees = {}
    functions = {}
    for hook in register["hooks"]:
        relative, symbol = hook["file"], hook["symbol"]
        key = f"{relative}:{symbol}"
        if relative not in functions:
            try:
                functions[relative] = _functions(_parse_source(root, relative, trees))
            except (OSError, SyntaxError):
                functions[relative] = {}
        node = functions[relative].get(symbol)
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            problems.append(f"missing hook: {key}")
            continue
        if signature(node) != hook["signature"]:
            problems.append(f"signature drift: {key}")
        literals = {
            child.value
            for child in ast.walk(node)
            if isinstance(child, ast.Constant) and isinstance(child.value, str)
        }
        for literal in hook.get("required_literals", []):
            if literal not in literals:
                problems.append(f"protocol drift: {key} -> {literal}")
        calls = _calls(node)
        for required in hook.get("required_calls", []):
            matches = [call for call in calls if _name(call.func) == required["callee"]]
            if not any(
                set(required.get("keywords", ())) <= {keyword.arg for keyword in call.keywords}
                and all(
                    any(
                        keyword.arg == name and ast.unparse(keyword.value) == value
                        for keyword in call.keywords
                    )
                    for name, value in required.get("keyword_values", {}).items()
                )
                and all(
                    index < len(call.args) and ast.unparse(call.args[index]) == argument
                    for index, argument in enumerate(required.get("arguments", ()))
                )
                for call in matches
            ):
                problems.append(f"missing required call: {key} -> {required['callee']}")
        ordered = hook.get("call_order", [])
        names = [_name(call.func) for call in calls]
        if ordered and (
            any(name not in names for name in ordered)
            or [names.index(name) for name in ordered]
            != sorted(names.index(name) for name in ordered if name in names)
        ):
            problems.append(f"security call order drift: {key}")
    actual = _source_inventory(root, trees)
    for category, entries in actual.items():
        expected, found = Counter(register[category]), Counter(entries)
        for entry in sorted((found - expected).elements()):
            problems.append(f"unclassified {category}: {entry}")
        for entry in sorted((expected - found).elements()):
            problems.append(f"missing {category}: {entry}")
    if not register["hooks"] or not register["routes"]:
        problems.append("incomplete compatibility register")
    return problems


def check_compatibility(root: Path = ROOT, app: Any | None = None) -> list[str]:
    """Offline gate. Pass the assembled protected application to check its routes."""
    problems = check_source_contracts(root)
    if app is None:
        return problems
    expected = {route["key"]: route for route in load_register(root)["routes"]}
    actual = route_inventory(app)
    found = Counter(route["key"] for route in actual)
    for route in actual:
        key = route["key"]
        if key not in expected:
            problems.append(f"unclassified route: {key}")
        elif any(route[field] != expected[key][field] for field in ("endpoint", "dependencies")):
            problems.append(f"route adapter drift: {key}")
        if found[key] > 1:
            problems.append(f"duplicate route: {key}")
    for key in sorted(expected.keys() - found.keys()):
        problems.append(f"missing route: {key}")
    return problems


def require_compatible_hooks(root: Path | None = None) -> None:
    """Fail protected activation without leaking paths, source, or credentials."""
    try:
        problems = check_source_contracts(root or ROOT)
    except (OSError, ValueError, KeyError, TypeError, SyntaxError):
        raise RuntimeError("Protected extension compatibility check failed") from None
    if problems:
        raise RuntimeError("Protected extension compatibility check failed") from None
