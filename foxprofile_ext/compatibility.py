"""Finite upstream seams: source contracts plus the assembled protected route table.

The register is reviewed data, never regenerated by the gate. Checks deliberately
ignore formatting and unrelated implementation changes. Behavioral security tests
remain necessary: an AST call contract alone cannot prove authorization works.
"""

